#pragma once
#include <chrono>
#include <variant>
#include <complex>
#include <string>
#include <vector>


namespace Sagax::SCG {

    struct SignalVariant {
        struct Null {
        };

        struct Noise {
            double span;
        };

        struct Tone {
        };

        struct Chirp {
            double span;
            double rate;
        };

        struct Pulse {
            double duty;
            double rate;
        };

        struct AudioFile {
            enum struct Modulation { IQ, FM, AM, PM };
            Modulation mod;
            std::string fileName;
        };

        struct IQFile {
            std::string fileName;
            // when false the file plays once and silence follows
            bool loop = true;
        };

        struct Zero {
        };

        // generated by the ssp gnss engine while the scenario plays
        struct GnssSpoofing {
            // the signals the engine can generate, each at its own nominal center
            enum struct Signal {
                gpsL1ca,
                gpsL2c,
                gpsL5,
                galE1,
                galE6,
                galE5b,
                galE5,
                galE5a,
                bdsB1c,
                bdsB1i,
                bdsB3i,
                bdsB2i,
                bdsB2a,
                gloG1,
                gloG2,
            };
            // t in seconds from the first sample, latitude and longitude in degrees,
            // altitude in meters
            struct Waypoint {
                double t;
                double latitude;
                double longitude;
                double altitude;
            };

            Signal signal;
            std::chrono::system_clock::time_point startTime; // utc of the first sample
            std::string ephemerisFile; // rinex navigation file
            // the first waypoint is at t = 0, after the last one the position holds
            std::vector<Waypoint> trajectory;
        };

        using T = std::variant<
            Null,
            Noise,
            Tone,
            Chirp,
            Pulse,
            AudioFile,
            IQFile,
            Zero,
            GnssSpoofing
        >;

        T variant;
    };
}



